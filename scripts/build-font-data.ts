/**
 * Generates src/render/generated/font-data.ts: woff2 subsets of Space Grotesk
 * and JetBrains Mono, per-character advance widths for text fitting, and the
 * WakaTime brand path. Run it after changing src/render/labels.ts:
 *
 *   pnpm build:font-data
 *
 * Subsetting and shaping need HarfBuzz (WebAssembly), which is far too slow for
 * a Worker's CPU budget, so it happens here once and the output is committed.
 * Downloads are cached in .cache/ (git-ignored).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Blob, Face, Font, Buffer as HbBuffer, shape, Variation } from 'harfbuzzjs';
import subsetFont from 'subset-font';
import { LABEL_CHARSET, VALUE_CHARSET } from '../src/render/labels.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = join(ROOT, '.cache');
const OUT = join(ROOT, 'src', 'render', 'generated', 'font-data.ts');

/** Same sources and simple-icons release tools/build-profile.mjs uses. */
const FONT_URLS = {
  SpaceGrotesk: 'https://github.com/google/fonts/raw/main/ofl/spacegrotesk/SpaceGrotesk%5Bwght%5D.ttf',
  JetBrainsMono: 'https://github.com/google/fonts/raw/main/ofl/jetbrainsmono/JetBrainsMono%5Bwght%5D.ttf',
} as const;
const WAKATIME_ICON_URL = 'https://cdn.jsdelivr.net/npm/simple-icons@16.35.0/icons/wakatime.svg';

interface FaceSpec {
  key: string;
  file: keyof typeof FONT_URLS;
  wght: number;
  family: string;
  fallback: string;
  charset: string;
}

const FACES: FaceSpec[] = [
  {
    key: 'd7',
    file: 'SpaceGrotesk',
    wght: 700,
    family: 'Space Grotesk',
    fallback: 'system-ui,sans-serif',
    charset: VALUE_CHARSET,
  },
  {
    key: 'm4',
    file: 'JetBrainsMono',
    wght: 400,
    family: 'JetBrains Mono',
    fallback: 'ui-monospace,monospace',
    charset: LABEL_CHARSET,
  },
];

async function cached(name: string, url: string): Promise<Buffer> {
  const path = join(CACHE, name);
  if (!existsSync(path)) {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`download failed: ${url} (HTTP ${res.status})`);
    mkdirSync(CACHE, { recursive: true });
    writeFileSync(path, new Uint8Array(await res.arrayBuffer()));
  }
  return readFileSync(path);
}

/** Advance of each character on its own, in em, at the face's weight. */
function advances(ttf: Buffer, wght: number, charset: string): Record<string, number> {
  const face = new Face(new Blob(ttf), 0);
  const font = new Font(face);
  font.setVariations([new Variation('wght', wght)]);
  const out: Record<string, number> = {};
  for (const ch of [...new Set(charset)].sort()) {
    const buf = new HbBuffer();
    buf.addText(ch);
    buf.guessSegmentProperties();
    shape(font, buf);
    const units = buf.getGlyphPositions().reduce((sum, p) => sum + p.xAdvance, 0);
    out[ch] = Math.round((units / face.upem) * 1e4) / 1e4;
  }
  return out;
}

const faces: string[] = [];
for (const spec of FACES) {
  const ttf = await cached(`${spec.file}.ttf`, FONT_URLS[spec.file]);
  const woff2: Buffer = await subsetFont(ttf, [...new Set(spec.charset)].join(''), {
    targetFormat: 'woff2',
    variationAxes: { wght: spec.wght },
  });
  const entry = {
    key: spec.key,
    family: spec.family,
    fallback: spec.fallback,
    woff2: woff2.toString('base64'),
    advances: advances(ttf, spec.wght, spec.charset),
  };
  faces.push(`  ${spec.key}: ${JSON.stringify(entry, null, 2).replace(/\n/g, '\n  ')},`);
  console.log(
    `${spec.key}: ${spec.family} ${spec.wght}, ${[...new Set(spec.charset)].length} chars, ${woff2.length} bytes woff2`,
  );
}

const iconSvg = (await cached('wakatime.svg', WAKATIME_ICON_URL)).toString('utf8');
const iconPath = /\sd="([^"]+)"/.exec(iconSvg)?.[1];
if (!iconPath) throw new Error('no <path d> in the WakaTime icon');

writeFileSync(
  OUT,
  [
    '// Generated by scripts/build-font-data.ts. Do not edit; run `pnpm build:font-data`.',
    "import type { FontFace } from '../fonts.ts';",
    '',
    'export const FONT_FACES = {',
    ...faces,
    '} satisfies Record<string, FontFace>;',
    '',
    `export const WAKATIME_ICON_PATH = ${JSON.stringify(iconPath)};`,
    '',
  ].join('\n'),
);
console.log(`wrote ${OUT}`);
